import type { ExportTable, WorkspaceExportSource } from '@agent-sales/contracts';
import { exportTable, type Database } from '@agent-sales/db';
import { workspaceId } from '@agent-sales/shared';

/**
 * The commerce module's part of the workspace data export (SET-10): products, variants, orders,
 * order lines and stay requests. Money is VND integers. Search text, PMS push errors, stock
 * bookkeeping, request fingerprints and versions are left out.
 */
export class CommerceExportSource implements WorkspaceExportSource {
  constructor(private readonly db: Database | null) {}

  exportTables(ws: string): readonly ExportTable[] {
    const db = this.db;
    if (!db) return [];
    const id = workspaceId(ws);
    return [
      exportTable(db, id, {
        file: 'products.csv',
        table: 'products',
        mediaColumns: ['image_urls'],
        columns: [
          { header: 'id', sql: 't.id' },
          { header: 'code', sql: 't.code' },
          { header: 'name', sql: 't.name' },
          { header: 'category', sql: 't.category' },
          { header: 'status', sql: 't.status' },
          { header: 'description', sql: 't.description' },
          { header: 'visible_to_bot', sql: 't.visible_to_bot' },
          { header: 'bot_instructions', sql: 't.bot_instructions' },
          { header: 'image_urls', sql: 't.image_urls' },
          { header: 'accommodation', sql: 't.accommodation' },
          { header: 'offering', sql: 't.offering' },
          { header: 'external_source', sql: 't.external_source' },
          { header: 'external_id', sql: 't.external_id' },
          { header: 'created_at', sql: 't.created_at', time: true },
          { header: 'updated_at', sql: 't.updated_at', time: true },
        ],
      }),
      exportTable(db, id, {
        file: 'product_variants.csv',
        table: 'product_variants',
        columns: [
          { header: 'id', sql: 't.id' },
          { header: 'product_id', sql: 't.product_id' },
          { header: 'product', sql: '(select p.name from products p where p.id = t.product_id)' },
          { header: 'sku', sql: 't.sku' },
          { header: 'name', sql: 't.name' },
          { header: 'price', sql: 't.price' },
          { header: 'cost', sql: 't.cost' },
          { header: 'weight_gram', sql: 't.weight_gram' },
          { header: 'position', sql: 't.position' },
          { header: 'external_id', sql: 't.external_id' },
          { header: 'archived_at', sql: 't.archived_at', time: true },
          { header: 'created_at', sql: 't.created_at', time: true },
          { header: 'updated_at', sql: 't.updated_at', time: true },
        ],
      }),
      exportTable(db, id, {
        file: 'orders.csv',
        table: 'orders',
        where: 't.deleted_at is null',
        columns: [
          { header: 'id', sql: 't.id' },
          { header: 'code', sql: 't.code' },
          { header: 'status', sql: 't.status' },
          { header: 'source', sql: 't.source' },
          { header: 'placed_at', sql: 't.placed_at', time: true },
          { header: 'customer_name', sql: "t.customer->>'name'" },
          { header: 'customer_phone', sql: "t.customer->>'phone'" },
          { header: 'customer_email', sql: "t.customer->>'email'" },
          { header: 'recipient_name', sql: "t.recipient->>'name'" },
          { header: 'recipient_phone', sql: "t.recipient->>'phone'" },
          { header: 'recipient_address', sql: "t.recipient->>'address'" },
          { header: 'recipient_ward', sql: "t.recipient->>'ward'" },
          { header: 'recipient_province', sql: "t.recipient->>'province'" },
          {
            header: 'warehouse',
            sql: '(select w.name from warehouses w where w.id = t.warehouse_id)',
          },
          { header: 'item_qty', sql: 't.item_qty' },
          { header: 'subtotal', sql: 't.subtotal' },
          { header: 'discount_type', sql: 't.discount_type' },
          { header: 'discount_value', sql: 't.discount_value' },
          { header: 'discount_amount', sql: 't.discount_amount' },
          { header: 'shipping_fee', sql: 't.shipping_fee' },
          { header: 'shipping_fee_charged', sql: 't.shipping_fee_charged' },
          { header: 'free_shipping', sql: 't.free_shipping' },
          { header: 'surcharge', sql: 't.surcharge' },
          { header: 'transfer_amount', sql: 't.transfer_amount' },
          { header: 'total', sql: 't.total' },
          { header: 'paid', sql: 't.paid' },
          { header: 'remaining', sql: 't.remaining' },
          { header: 'cod_amount', sql: 't.cod_amount' },
          { header: 'cost_total', sql: 't.cost_total' },
          { header: 'carrier', sql: 't.carrier' },
          { header: 'tracking_code', sql: 't.tracking_code' },
          { header: 'expected_delivery_at', sql: 't.expected_delivery_at', time: true },
          { header: 'note_internal', sql: 't.note_internal' },
          { header: 'note_print', sql: 't.note_print' },
          { header: 'created_by', sql: 't.created_by_name' },
          { header: 'created_by_kind', sql: 't.created_by_kind' },
          { header: 'conversation_id', sql: 't.conversation_id' },
          { header: 'review_state', sql: 't.review_state' },
          { header: 'reviewed_by', sql: 't.reviewed_by_name' },
          { header: 'reviewed_at', sql: 't.reviewed_at', time: true },
          { header: 'external_source', sql: 't.external_source' },
          { header: 'external_code', sql: 't.external_code' },
          { header: 'external_status', sql: 't.external_status' },
          { header: 'confirmed_at', sql: 't.confirmed_at', time: true },
          { header: 'cancelled_at', sql: 't.cancelled_at', time: true },
          { header: 'created_at', sql: 't.created_at', time: true },
          { header: 'updated_at', sql: 't.updated_at', time: true },
        ],
      }),
      exportTable(db, id, {
        file: 'order_items.csv',
        table: 'order_items',
        where: 'exists (select 1 from orders o where o.id = t.order_id and o.deleted_at is null)',
        columns: [
          { header: 'id', sql: 't.id' },
          { header: 'order_id', sql: 't.order_id' },
          { header: 'order_code', sql: '(select o.code from orders o where o.id = t.order_id)' },
          { header: 'variant_id', sql: 't.variant_id' },
          { header: 'product_name', sql: 't.product_name' },
          { header: 'variant_name', sql: 't.variant_name' },
          { header: 'sku', sql: 't.sku' },
          { header: 'qty', sql: 't.qty' },
          { header: 'unit_price', sql: 't.unit_price' },
          { header: 'unit_cost', sql: 't.unit_cost' },
          { header: 'line_total', sql: 't.line_total' },
          { header: 'position', sql: 't.position' },
        ],
      }),
      exportTable(db, id, {
        file: 'stay_requests.csv',
        table: 'stay_requests',
        columns: [
          { header: 'id', sql: 't.id' },
          { header: 'property_id', sql: 't.property_id' },
          { header: 'property_name', sql: 't.property_name' },
          { header: 'guest_name', sql: 't.guest_name' },
          { header: 'guest_phone', sql: 't.guest_phone' },
          { header: 'check_in', sql: 't.check_in::text' },
          { header: 'check_out', sql: 't.check_out::text' },
          { header: 'nights', sql: "(t.quote->>'nights')::int" },
          { header: 'adults', sql: "(t.party->>'adults')::int" },
          { header: 'children', sql: "(t.party->>'children')::int" },
          { header: 'child_ages', sql: "coalesce(t.party->'childAges', '[]'::jsonb)" },
          { header: 'quoted_total', sql: "(t.quote->>'baseTotal')::bigint" },
          { header: 'agreed_total', sql: 't.agreed_total' },
          { header: 'status', sql: 't.status' },
          { header: 'note', sql: 't.note' },
          { header: 'created_at', sql: 't.created_at', time: true },
          { header: 'updated_at', sql: 't.updated_at', time: true },
        ],
      }),
    ];
  }
}
