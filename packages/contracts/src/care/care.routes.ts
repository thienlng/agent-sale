import { defineRoutes } from '../common/routes.js';
import { ImpactQuery, ImpactResponse } from '../brain/brain.schema.js';
import {
  AiDoneResponse,
  ApproveCareMessageRequest,
  BulkApproveCareMessagesRequest,
  BulkApproveCareMessagesResponse,
  CareMessageDto,
  CareSettingsResponse,
  CareTemplateDto,
  UpdateCareTemplateRequest,
} from './care.schema.js';

export const careRoutes = defineRoutes([
  {
    method: 'get',
    path: '/care/settings',
    assistant: {
      use: 'read',
      when: 'The automatic follow-up templates, quiet hours, the daily cap and its usage today',
    },
    summary: 'Care agent settings: templates, quiet hours, daily cap and usage',
    tag: 'care',
    auth: true,
    workspaceScoped: true,
    responses: { 200: CareSettingsResponse },
  },
  {
    method: 'put',
    path: '/care/templates/{key}',
    assistant: {
      use: 'write',
      when: 'Turn a follow-up template on or off, or change its short instruction',
    },
    summary: 'Turn a follow-up template on/off and set its instruction (owner and admin)',
    tag: 'care',
    auth: true,
    workspaceScoped: true,
    body: UpdateCareTemplateRequest,
    responses: { 200: CareTemplateDto },
  },
  {
    method: 'post',
    path: '/today/approval/{id}/approve',
    assistant: { use: 'never' },
    summary: 'Send a drafted follow-up now ("Gửi"; "Sửa rồi gửi" with the edited text)',
    tag: 'care',
    auth: true,
    workspaceScoped: true,
    body: ApproveCareMessageRequest,
    responses: { 200: CareMessageDto },
  },
  {
    method: 'post',
    path: '/today/approval/{id}/reject',
    assistant: { use: 'never' },
    summary: 'Drop a drafted follow-up ("Bỏ")',
    tag: 'care',
    auth: true,
    workspaceScoped: true,
    responses: { 200: CareMessageDto },
  },
  {
    method: 'post',
    path: '/today/approval/approve-all',
    assistant: { use: 'never' },
    summary: 'Send the drafted follow-ups the caller sees ("Gửi tất cả", at most 50)',
    tag: 'care',
    auth: true,
    workspaceScoped: true,
    body: BulkApproveCareMessagesRequest,
    responses: { 200: BulkApproveCareMessagesResponse },
  },
  {
    method: 'get',
    path: '/today/ai-done',
    assistant: {
      use: 'read',
      when: 'Follow-ups the AI sent today on its own (act-and-report level) and whether customers answered',
    },
    summary: '"AI đã làm": follow-ups the AI sent today and the customers\' reactions',
    tag: 'care',
    auth: true,
    workspaceScoped: true,
    responses: { 200: AiDoneResponse },
  },
  {
    method: 'get',
    path: '/brain/impact',
    assistant: {
      use: 'read',
      when: 'Orders, bookings and revenue that followed an AI touch (today, 7 or 30 days)',
    },
    summary: '"Rapiz đã mang lại": orders and revenue after an AI touch, follow-ups and replies',
    tag: 'care',
    auth: true,
    workspaceScoped: true,
    query: ImpactQuery,
    responses: { 200: ImpactResponse },
  },
]);
