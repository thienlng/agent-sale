import { defineRoutes } from '../common/routes.js';
import {
  AdminAccountDetail,
  AdminAccountList,
  AdminAccountListQuery,
  AdminAuditList,
  AdminAuditQuery,
  AdminOverrideDto,
  AdminPaymentDto,
  AdminPaymentList,
  AdminPaymentListQuery,
  AdminPlanDto,
  AdminPlanList,
  AdminReasonRequest,
  AdminSubscriptionDto,
  ArchivePlanRequest,
  BillingSettingsDto,
  ConfirmPaymentRequest,
  CreatePaymentRequest,
  CreatePlanRequest,
  ExtendTrialRequest,
  PublishPlanVersionRequest,
  PutBillingSettingsRequest,
  PutOverrideRequest,
  SetAccountPlanRequest,
  SetAccountStatusRequest,
} from './backoffice.schema.js';

/** Platform back-office (ADR-021 §6). Platform admins only (others get 404). */
export const backofficeRoutes = defineRoutes([
  // Plan catalog
  {
    method: 'get',
    path: '/admin/plans',
    summary: 'Plan catalog: latest version of each plan and versions that still have subscribers',
    tag: 'admin',
    auth: true,
    responses: { 200: AdminPlanList },
  },
  {
    method: 'post',
    path: '/admin/plans',
    summary: 'Create a plan (version 1)',
    tag: 'admin',
    auth: true,
    body: CreatePlanRequest,
    responses: { 201: AdminPlanDto },
  },
  {
    method: 'post',
    path: '/admin/plans/{code}/versions',
    summary: 'Publish the next version of a plan; current subscribers keep theirs',
    tag: 'admin',
    auth: true,
    body: PublishPlanVersionRequest,
    responses: { 201: AdminPlanDto },
  },
  {
    method: 'post',
    path: '/admin/plans/{code}/archive',
    summary: 'Hide a plan from new sales, or show it again',
    tag: 'admin',
    auth: true,
    body: ArchivePlanRequest,
    responses: { 200: AdminPlanDto },
  },
  // Settings
  {
    method: 'get',
    path: '/admin/billing-settings',
    summary: 'Trial, lifecycle, bank account and HQ sync settings',
    tag: 'admin',
    auth: true,
    responses: { 200: BillingSettingsDto },
  },
  {
    method: 'put',
    path: '/admin/billing-settings',
    summary: 'Replace the billing settings',
    tag: 'admin',
    auth: true,
    body: PutBillingSettingsRequest,
    responses: { 200: BillingSettingsDto },
  },
  // Accounts
  {
    method: 'get',
    path: '/admin/accounts',
    summary: 'Accounts with owner, plan and status',
    tag: 'admin',
    auth: true,
    query: AdminAccountListQuery,
    responses: { 200: AdminAccountList },
  },
  {
    method: 'get',
    path: '/admin/accounts/{accountId}',
    summary: 'One account: businesses, members, subscription, overrides, usage, payments, audit',
    tag: 'admin',
    auth: true,
    responses: { 200: AdminAccountDetail },
  },
  {
    method: 'post',
    path: '/admin/accounts/{accountId}/plan',
    summary: "Set the account's plan and period",
    tag: 'admin',
    auth: true,
    body: SetAccountPlanRequest,
    responses: { 200: AdminSubscriptionDto },
  },
  {
    method: 'post',
    path: '/admin/accounts/{accountId}/trial',
    summary: 'Extend the trial until a date',
    tag: 'admin',
    auth: true,
    body: ExtendTrialRequest,
    responses: { 200: AdminSubscriptionDto },
  },
  {
    method: 'put',
    path: '/admin/accounts/{accountId}/overrides/{key}',
    summary: 'Grant an entitlement override to the account',
    tag: 'admin',
    auth: true,
    body: PutOverrideRequest,
    responses: { 200: AdminOverrideDto },
  },
  {
    method: 'delete',
    path: '/admin/accounts/{accountId}/overrides/{key}',
    summary: 'Remove an entitlement override (reason in the body)',
    tag: 'admin',
    auth: true,
    body: AdminReasonRequest,
    responses: { 204: null },
  },
  {
    method: 'post',
    path: '/admin/accounts/{accountId}/status',
    summary: 'Suspend or reactivate an account',
    tag: 'admin',
    auth: true,
    body: SetAccountStatusRequest,
    responses: { 204: null },
  },
  // Payments (VietQR, manual confirm)
  {
    method: 'get',
    path: '/admin/payments',
    summary: 'Payment requests, newest first',
    tag: 'admin',
    auth: true,
    query: AdminPaymentListQuery,
    responses: { 200: AdminPaymentList },
  },
  {
    method: 'post',
    path: '/admin/accounts/{accountId}/payments',
    summary: 'Create a VietQR payment request for a plan and period',
    tag: 'admin',
    auth: true,
    body: CreatePaymentRequest,
    responses: { 201: AdminPaymentDto },
  },
  {
    method: 'post',
    path: '/admin/payments/{paymentId}/confirm',
    summary: 'Confirm a received transfer and apply the plan',
    tag: 'admin',
    auth: true,
    body: ConfirmPaymentRequest,
    responses: { 200: AdminPaymentDto },
  },
  {
    method: 'post',
    path: '/admin/payments/{paymentId}/cancel',
    summary: 'Cancel a pending payment request',
    tag: 'admin',
    auth: true,
    body: AdminReasonRequest,
    responses: { 200: AdminPaymentDto },
  },
  // Audit
  {
    method: 'get',
    path: '/admin/audit',
    summary: 'Platform operator audit trail',
    tag: 'admin',
    auth: true,
    query: AdminAuditQuery,
    responses: { 200: AdminAuditList },
  },
]);
