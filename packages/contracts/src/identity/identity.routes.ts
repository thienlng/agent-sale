import { defineRoutes } from '../common/routes.js';
import {
  AuthResponse,
  BootstrapResponse,
  LoginRequest,
  MfaEnableRequest,
  MfaReauthRequest,
  MfaSetup,
  MfaSetupRequest,
  MfaStatus,
  RecoveryCodes,
  RefreshRequest,
  SignupRequest,
  UserDto,
} from './identity.schema.js';

export const identityRoutes = defineRoutes([
  {
    method: 'post',
    path: '/auth/signup',
    summary: 'Create a user, their first workspace (owner) and a session',
    tag: 'auth',
    auth: false,
    body: SignupRequest,
    responses: { 201: AuthResponse },
  },
  {
    method: 'post',
    path: '/auth/login',
    summary: 'Email + password login; sets the refresh cookie (web) or returns it (native)',
    tag: 'auth',
    auth: false,
    body: LoginRequest,
    responses: { 200: AuthResponse },
    // 401 with details.reason = mfa_required | mfa_invalid when the account has two-factor on.
  },
  {
    method: 'post',
    path: '/auth/refresh',
    summary: 'Rotate the refresh token and issue a new access token',
    tag: 'auth',
    auth: false,
    body: RefreshRequest,
    responses: { 200: AuthResponse },
  },
  {
    method: 'post',
    path: '/auth/logout',
    summary: 'Revoke the current session and clear the refresh cookie',
    tag: 'auth',
    auth: true,
    responses: { 204: null },
  },
  {
    method: 'get',
    path: '/me',
    summary: 'The authenticated user',
    tag: 'auth',
    auth: true,
    responses: { 200: UserDto },
  },
  {
    method: 'get',
    path: '/bootstrap',
    summary: 'User + workspace memberships, fetched once before the SPA renders',
    tag: 'auth',
    auth: true,
    responses: { 200: BootstrapResponse },
  },
  {
    method: 'get',
    path: '/auth/mfa',
    summary: 'Two-factor status of the signed-in user',
    tag: 'auth',
    auth: true,
    responses: { 200: MfaStatus },
  },
  {
    method: 'post',
    path: '/auth/mfa/setup',
    summary: 'Start two-factor setup (password required); returns the secret once',
    tag: 'auth',
    auth: true,
    body: MfaSetupRequest,
    responses: { 200: MfaSetup },
  },
  {
    method: 'post',
    path: '/auth/mfa/enable',
    summary: 'Confirm the first code; turns it on and returns the recovery codes once',
    tag: 'auth',
    auth: true,
    body: MfaEnableRequest,
    responses: { 200: RecoveryCodes },
  },
  {
    method: 'post',
    path: '/auth/mfa/disable',
    summary: 'Turn two-factor off (password + current code)',
    tag: 'auth',
    auth: true,
    body: MfaReauthRequest,
    responses: { 204: null },
  },
  {
    method: 'post',
    path: '/auth/mfa/recovery-codes',
    summary: 'Replace the recovery codes (password + current code); returns them once',
    tag: 'auth',
    auth: true,
    body: MfaReauthRequest,
    responses: { 200: RecoveryCodes },
  },
]);
