import { defineRoutes, type RouteContract } from '../common/routes.js';
import {
  AdjustStockRequest,
  BotProductsDto,
  ChangeOrderStatusRequest,
  CreateOrderRequest,
  OrderDto,
  OrderListQuery,
  OrderListResponse,
  ProductDto,
  ProductListQuery,
  ProductListResponse,
  SetBotProductsRequest,
  UpdateOrderRequest,
  UpdateProductBotSettingsRequest,
  UpsertProductRequest,
  UpsertWarehouseRequest,
  VariantSearchQuery,
  VariantSearchResponse,
  WarehouseDto,
  WarehouseList,
} from './commerce.schema.js';
import { ApproveOrderRequest, OrderReviewCountResponse } from './order-review.schema.js';
import { OrderOverviewQuery, OrderOverviewResponse } from './order-overview.schema.js';
import { UploadProductImageRequest, UploadProductImageResponse } from './product-images.schema.js';
import { OrderSettingsDto } from './order-settings.schema.js';

const scoped = { auth: true, workspaceScoped: true } as const;
const route = <T extends Omit<RouteContract, 'auth' | 'workspaceScoped'>>(r: T) => ({
  ...r,
  ...scoped,
});

export const commerceRoutes = defineRoutes([
  route({
    method: 'post',
    path: '/products/images',
    summary: 'Upload a product picture to Rapiz storage and get its public URL',
    tag: 'commerce',
    body: UploadProductImageRequest,
    responses: { 201: UploadProductImageResponse },
  }),
  route({
    method: 'get',
    path: '/warehouses',
    apiKey: true,
    summary: 'Warehouses',
    tag: 'commerce',
    responses: { 200: WarehouseList },
  }),
  route({
    method: 'post',
    path: '/warehouses',
    summary: 'Add a warehouse (the first one becomes the default)',
    tag: 'commerce',
    body: UpsertWarehouseRequest,
    responses: { 201: WarehouseDto },
  }),
  route({
    method: 'patch',
    path: '/warehouses/{warehouseId}',
    summary: 'Edit a warehouse or make it the default',
    tag: 'commerce',
    body: UpsertWarehouseRequest,
    responses: { 200: WarehouseDto },
  }),
  route({
    method: 'delete',
    path: '/warehouses/{warehouseId}',
    summary: 'Delete an empty, non-default warehouse',
    tag: 'commerce',
    responses: { 204: null },
  }),

  route({
    method: 'get',
    path: '/products',
    apiKey: true,
    summary: 'Product catalog (search, pages)',
    tag: 'commerce',
    query: ProductListQuery,
    responses: { 200: ProductListResponse },
  }),
  route({
    method: 'post',
    path: '/products',
    apiKey: true,
    summary: 'Create a product with its variants',
    tag: 'commerce',
    body: UpsertProductRequest,
    responses: { 201: ProductDto },
  }),
  route({
    method: 'get',
    path: '/products/{productId}',
    apiKey: true,
    summary: 'One product with variants and stock',
    tag: 'commerce',
    responses: { 200: ProductDto },
  }),
  route({
    method: 'put',
    path: '/products/{productId}',
    apiKey: true,
    summary: 'Replace a product and its variants (missing variants are archived)',
    tag: 'commerce',
    body: UpsertProductRequest,
    responses: { 200: ProductDto },
  }),
  route({
    method: 'patch',
    path: '/products/{productId}/bot-settings',
    summary: "Change only a product's bot fields (visibleToBot, botInstructions); any product",
    tag: 'commerce',
    body: UpdateProductBotSettingsRequest,
    responses: { 200: ProductDto },
  }),
  route({
    method: 'post',
    path: '/products/{productId}/stock',
    apiKey: true,
    summary: 'Set the counted stock of a variant in a warehouse',
    tag: 'commerce',
    body: AdjustStockRequest,
    responses: { 200: ProductDto },
  }),
  route({
    method: 'get',
    path: '/bots/{botId}/products',
    summary: "Products selected for a bot (used when the bot's catalogMode is 'selected')",
    tag: 'commerce',
    responses: { 200: BotProductsDto },
  }),
  route({
    method: 'put',
    path: '/bots/{botId}/products',
    summary: 'Replace the products selected for a bot',
    tag: 'commerce',
    body: SetBotProductsRequest,
    responses: { 200: BotProductsDto },
  }),
  route({
    method: 'get',
    path: '/product-variants',
    apiKey: true,
    summary: 'Variant picker for the order form',
    tag: 'commerce',
    query: VariantSearchQuery,
    responses: { 200: VariantSearchResponse },
  }),

  route({
    method: 'get',
    path: '/orders',
    apiKey: true,
    summary: 'Orders with status counts and totals',
    tag: 'commerce',
    query: OrderListQuery,
    responses: { 200: OrderListResponse },
  }),
  route({
    method: 'post',
    path: '/orders',
    apiKey: true,
    summary: 'Create an order (reserves stock)',
    tag: 'commerce',
    body: CreateOrderRequest,
    responses: { 201: OrderDto },
  }),
  route({
    method: 'get',
    path: '/orders/overview',
    summary: 'Sales overview for a date range',
    tag: 'commerce',
    query: OrderOverviewQuery,
    responses: { 200: OrderOverviewResponse },
  }),
  route({
    method: 'get',
    path: '/orders/review-count',
    summary: 'How many bot orders wait for review',
    tag: 'commerce',
    responses: { 200: OrderReviewCountResponse },
  }),
  route({
    method: 'get',
    path: '/orders/{orderId}',
    apiKey: true,
    summary: 'One order with items and status history',
    tag: 'commerce',
    responses: { 200: OrderDto },
  }),
  route({
    method: 'patch',
    path: '/orders/{orderId}',
    apiKey: true,
    summary: 'Edit people, shipping, payment received or notes',
    tag: 'commerce',
    body: UpdateOrderRequest,
    responses: { 200: OrderDto },
  }),
  route({
    method: 'post',
    path: '/orders/{orderId}/status',
    apiKey: true,
    summary: 'Change the status (moves stock as needed)',
    tag: 'commerce',
    body: ChangeOrderStatusRequest,
    responses: { 200: OrderDto },
  }),
  route({
    method: 'post',
    path: '/orders/{orderId}/approve',
    summary: 'Approve a bot order, or revert the approval',
    tag: 'commerce',
    body: ApproveOrderRequest,
    responses: { 200: OrderDto },
  }),

  route({
    method: 'get',
    path: '/order-settings',
    summary: 'Order status settings',
    tag: 'commerce',
    responses: { 200: OrderSettingsDto },
  }),
  route({
    method: 'put',
    path: '/order-settings',
    summary: 'Update order status settings',
    tag: 'commerce',
    body: OrderSettingsDto,
    responses: { 200: OrderSettingsDto },
  }),
]);
