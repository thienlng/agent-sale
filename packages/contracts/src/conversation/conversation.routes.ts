import { defineRoutes } from '../common/routes.js';
import {
  ConversationListQuery,
  ConversationListResponse,
  ConversationDetailDto,
  InboxMessageDto,
  SendInboxMessageRequest,
  AddConversationNoteRequest,
  AssignConversationTagRequest,
  ConversationTagAssignmentDto,
  ConversationTagAssignmentList,
  UpdateConversationRequest,
  ConversationDto,
  BulkConversationRequest,
  BulkConversationResponse,
  SetConversationContactRequest,
} from './conversation.schema.js';
const scoped = { auth: true, workspaceScoped: true, tag: 'conversation' } as const;
export const conversationRoutes = defineRoutes([
  {
    ...scoped,
    method: 'get',
    path: '/conversations',
    assistant: {
      use: 'read',
      when: 'The owner asks about inbox conversations: unread, waiting for staff, assigned to someone, by channel or by customer.',
    },
    summary: 'Workspace inbox',
    query: ConversationListQuery,
    responses: { 200: ConversationListResponse },
  },
  {
    ...scoped,
    method: 'post',
    path: '/conversations/bulk',
    assistant: { use: 'never' },
    summary: 'Run one action on several conversations; per-conversation results',
    body: BulkConversationRequest,
    responses: { 200: BulkConversationResponse },
  },
  {
    ...scoped,
    method: 'get',
    path: '/conversations/{id}',
    assistant: {
      use: 'read',
      when: 'Read one conversation with its recent messages, for example to summarise what a customer asked.',
    },
    summary: 'Conversation and recent messages',
    responses: { 200: ConversationDetailDto },
  },
  {
    ...scoped,
    method: 'patch',
    path: '/conversations/{id}',
    assistant: {
      use: 'write',
      when: 'The owner asks to hand a conversation to the bot or to staff, assign it, resolve it, star it or set a follow-up.',
    },
    summary: 'Take over, assign, resolve or annotate',
    body: UpdateConversationRequest,
    responses: { 200: ConversationDto },
  },
  {
    ...scoped,
    method: 'post',
    path: '/conversations/{id}/messages',
    assistant: { use: 'never' },
    summary: 'Send a reply and pause automation',
    body: SendInboxMessageRequest,
    responses: { 201: InboxMessageDto },
  },
  {
    ...scoped,
    method: 'post',
    path: '/conversations/{id}/read',
    assistant: { use: 'never' },
    summary: 'Mark read for the whole shop (unread count 0, records who)',
    responses: { 200: ConversationDto },
  },
  {
    ...scoped,
    method: 'post',
    path: '/conversations/{id}/unread',
    assistant: { use: 'never' },
    summary: 'Mark unread again (unread count at least 1)',
    responses: { 200: ConversationDto },
  },
  {
    ...scoped,
    method: 'post',
    path: '/conversations/{id}/notes',
    assistant: {
      use: 'write',
      when: 'The owner asks to add an internal note to a conversation (never sent to the customer).',
    },
    summary: 'Add an internal note to the timeline',
    body: AddConversationNoteRequest,
    responses: { 201: ConversationDto },
  },
  {
    ...scoped,
    method: 'put',
    path: '/conversations/{id}/contact',
    assistant: {
      use: 'write',
      when: 'The owner asks to link a conversation to a customer record, or to unlink it.',
    },
    summary: 'Link the conversation to a customer of this business, or unlink it (null)',
    body: SetConversationContactRequest,
    responses: { 200: ConversationDto },
  },
  {
    ...scoped,
    method: 'get',
    path: '/conversations/{id}/tags',
    assistant: { use: 'read', when: 'Which tags a conversation has.' },
    summary: 'Active tags of a conversation',
    responses: { 200: ConversationTagAssignmentList },
  },
  {
    ...scoped,
    method: 'post',
    path: '/conversations/{id}/tags',
    assistant: { use: 'write', when: 'The owner asks to tag a conversation.' },
    summary: 'Tag a conversation (idempotent per tag; remove with /tag-assignments/{id}/remove)',
    body: AssignConversationTagRequest,
    responses: { 200: ConversationTagAssignmentDto, 201: ConversationTagAssignmentDto },
  },
]);
