import { defineRoutes } from '../common/routes.js';
import {
  ApiKeyDto,
  ApiKeyList,
  CreateApiKeyRequest,
  CreatedApiKey,
  CreateWebhookEndpointRequest,
  UpdateWebhookEndpointRequest,
  WebhookDeliveryDto,
  WebhookDeliveryPage,
  WebhookDeliveryQuery,
  WebhookEndpointDto,
  WebhookEndpointList,
  WebhookEndpointWithSecret,
} from './developer.schema.js';

/** Settings → Developers (ADR-022). Every route needs `developer.manage`; never reachable by an API key. */
const scoped = { tag: 'developer', auth: true, workspaceScoped: true } as const;

export const developerRoutes = defineRoutes([
  {
    ...scoped,
    method: 'get',
    path: '/api-keys',
    assistant: { use: 'never' },
    summary: 'API keys of the workspace',
    responses: { 200: ApiKeyList },
  },
  {
    ...scoped,
    method: 'post',
    path: '/api-keys',
    assistant: { use: 'never' },
    summary: 'Create an API key (the full key is returned once)',
    body: CreateApiKeyRequest,
    responses: { 201: CreatedApiKey },
  },
  {
    ...scoped,
    method: 'post',
    path: '/api-keys/{id}/revoke',
    assistant: { use: 'never' },
    summary: 'Revoke an API key',
    responses: { 200: ApiKeyDto },
  },
  {
    ...scoped,
    method: 'get',
    path: '/webhook-endpoints',
    assistant: { use: 'never' },
    summary: 'Webhook endpoints of the workspace',
    responses: { 200: WebhookEndpointList },
  },
  {
    ...scoped,
    method: 'post',
    path: '/webhook-endpoints',
    assistant: { use: 'never' },
    summary: 'Add a webhook endpoint (the signing secret is returned once)',
    body: CreateWebhookEndpointRequest,
    responses: { 201: WebhookEndpointWithSecret },
  },
  {
    ...scoped,
    method: 'patch',
    path: '/webhook-endpoints/{id}',
    assistant: { use: 'never' },
    summary: 'Change a webhook endpoint (URL, events, enabled)',
    body: UpdateWebhookEndpointRequest,
    responses: { 200: WebhookEndpointDto },
  },
  {
    ...scoped,
    method: 'delete',
    path: '/webhook-endpoints/{id}',
    assistant: { use: 'never' },
    summary: 'Delete a webhook endpoint and its delivery log',
    responses: { 204: null },
  },
  {
    ...scoped,
    method: 'post',
    path: '/webhook-endpoints/{id}/rotate-secret',
    assistant: { use: 'never' },
    summary: 'Rotate the signing secret (the old one keeps signing for 24 h)',
    responses: { 200: WebhookEndpointWithSecret },
  },
  {
    ...scoped,
    method: 'post',
    path: '/webhook-endpoints/{id}/test',
    assistant: { use: 'never' },
    summary: 'Send a `webhook.test` event to the endpoint',
    responses: { 202: WebhookDeliveryDto },
  },
  {
    ...scoped,
    method: 'get',
    path: '/webhook-endpoints/{id}/deliveries',
    assistant: { use: 'never' },
    summary: 'Delivery log of an endpoint, newest first',
    query: WebhookDeliveryQuery,
    responses: { 200: WebhookDeliveryPage },
  },
  {
    ...scoped,
    method: 'post',
    path: '/webhook-deliveries/{id}/resend',
    assistant: { use: 'never' },
    summary: 'Send a delivery again (same event id)',
    responses: { 202: WebhookDeliveryDto },
  },
]);
