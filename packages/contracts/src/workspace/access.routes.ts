import { defineRoutes } from '../common/routes.js';
import {
  AcceptedInvitation,
  AcceptInvitationRequest,
  ChangeMemberRoleRequest,
  CreatedInvitation,
  CreateInvitationRequest,
  InvitationDto,
  InvitationList,
  InvitationPreview,
  MemberDto,
  MemberList,
  RemovalPreview,
  RemoveMemberRequest,
} from './access.schema.js';

const scoped = { tag: 'workspace', auth: true, workspaceScoped: true } as const;

export const accessRoutes = defineRoutes([
  {
    method: 'get',
    path: '/members',
    assistant: { use: 'read', when: 'Who works in the business and with which role.' },
    summary: 'Members of the workspace',
    ...scoped,
    responses: { 200: MemberList },
  },
  {
    method: 'patch',
    path: '/members/{userId}',
    assistant: { use: 'never' },
    summary: 'Change a member role',
    ...scoped,
    body: ChangeMemberRoleRequest,
    responses: { 200: MemberDto },
  },
  {
    method: 'get',
    path: '/members/{userId}/removal-preview',
    assistant: { use: 'never' },
    summary: 'What removing a member does to the customers they own',
    ...scoped,
    responses: { 200: RemovalPreview },
  },
  {
    method: 'post',
    path: '/members/{userId}/remove',
    assistant: { use: 'never' },
    summary: 'Remove a member (their work stays; customers go where the request says)',
    ...scoped,
    body: RemoveMemberRequest,
    responses: { 200: MemberDto },
  },
  {
    method: 'get',
    path: '/invitations',
    assistant: {
      use: 'read',
      when: 'Invitations sent to join the business and whether they are pending, accepted or expired.',
    },
    summary: 'Invitations of the workspace',
    ...scoped,
    responses: { 200: InvitationList },
  },
  {
    method: 'post',
    path: '/invitations',
    assistant: { use: 'never' },
    summary: 'Invite someone by email (returns the link secret once)',
    ...scoped,
    body: CreateInvitationRequest,
    responses: { 201: CreatedInvitation },
  },
  {
    method: 'post',
    path: '/invitations/{invitationId}/resend',
    assistant: { use: 'never' },
    summary: 'New link for the same email and role (the old one stops working)',
    ...scoped,
    responses: { 200: CreatedInvitation },
  },
  {
    method: 'post',
    path: '/invitations/{invitationId}/revoke',
    assistant: { use: 'never' },
    summary: 'Revoke a pending invitation',
    ...scoped,
    responses: { 200: InvitationDto },
  },
  {
    method: 'get',
    path: '/invitation-links/{token}',
    summary: 'Preview an invitation (signed in, not a member yet)',
    tag: 'workspace',
    auth: true,
    responses: { 200: InvitationPreview },
  },
  {
    method: 'post',
    path: '/invitation-links/accept',
    summary: 'Join the workspace of an invitation sent to your email',
    tag: 'workspace',
    auth: true,
    body: AcceptInvitationRequest,
    responses: { 200: AcceptedInvitation },
  },
]);
