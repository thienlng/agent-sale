import {
  FanpageSettings,
  FanpagePost,
  FanpageAction,
  FanpageManualAction,
  FanpageCommentListQuery,
  FanpageCommentPage,
  FanpageCommentDetail,
  FanpageCommentSource,
  FanpageCommentPostPage,
  FanpageCommentPostsQuery,
} from './fanpage.schema.js';
import { z } from 'zod';
import { defineRoutes } from '../common/routes.js';
import {
  ChannelListQuery,
  ChannelListResponse,
  ChannelConnectionDto,
  ConnectChannelResponse,
  DiscoveryDto,
  SelectChannelRequest,
  UpdateChannelRequest,
} from './channel.schema.js';
import { CreateWebsiteRequest, UpdateWebsiteRequest } from './website.schema.js';
const scoped = { auth: true, workspaceScoped: true, tag: 'channel' } as const;
export const channelRoutes = defineRoutes([
  {
    ...scoped,
    method: 'get',
    path: '/channels/{id}/fanpage/settings',
    assistant: {
      use: 'read',
      when: 'Check whether a Facebook Page auto-replies to comments, hides them, and which keywords or posts are excluded.',
    },
    summary: 'Facebook comment automation settings',
    responses: { 200: FanpageSettings },
  },
  {
    ...scoped,
    method: 'patch',
    path: '/channels/{id}/fanpage/settings',
    assistant: {
      use: 'write',
      when: 'The owner asks to turn Facebook comment auto-replies or hiding on or off, or to change hide keywords or excluded posts.',
    },
    summary: 'Configure Facebook comment automation',
    body: FanpageSettings,
    responses: { 200: FanpageSettings },
  },
  {
    ...scoped,
    method: 'get',
    path: '/channels/{id}/fanpage/posts',
    assistant: {
      use: 'read',
      when: 'The owner asks about the latest posts of a connected Facebook Page.',
    },
    summary: 'Latest 50 Page-owned posts',
    responses: { 200: z.object({ data: z.array(FanpagePost) }) },
  },
  {
    ...scoped,
    method: 'get',
    path: '/channels/{id}/fanpage/comments',
    assistant: {
      use: 'read',
      when: 'The owner asks about comments received on a Facebook Page, optionally for one post or containing some text.',
    },
    summary: 'Stored received comments: newest 100, or cursor pages filtered by post/text',
    query: FanpageCommentListQuery,
    responses: { 200: FanpageCommentPage },
  },
  {
    ...scoped,
    method: 'get',
    path: '/channels/{id}/fanpage/comments/{commentId}',
    assistant: {
      use: 'read',
      when: 'Details of one stored Facebook comment and its parent comment.',
    },
    summary: 'One stored comment and its stored parent, read without side effects',
    responses: { 200: FanpageCommentDetail },
  },
  {
    ...scoped,
    method: 'get',
    path: '/channels/{id}/fanpage/comments/{commentId}/source',
    assistant: { use: 'never' },
    summary: 'Fresh read-only Facebook lookup of the comment post and thread',
    responses: { 200: FanpageCommentSource },
  },
  {
    ...scoped,
    method: 'get',
    path: '/channels/{id}/fanpage/comment-posts',
    assistant: {
      use: 'read',
      when: 'Which Facebook posts received comments recently, most active first.',
    },
    summary: 'Posts known from stored comments, newest activity first, paginated',
    query: FanpageCommentPostsQuery,
    responses: { 200: FanpageCommentPostPage },
  },
  {
    ...scoped,
    method: 'post',
    path: '/channels/{id}/fanpage/comments/{commentId}/actions',
    assistant: { use: 'never' },
    summary: 'Staff reply or moderation override',
    body: FanpageManualAction,
    responses: { 201: z.object({ action: FanpageAction.nullable() }) },
  },
  {
    ...scoped,
    method: 'get',
    path: '/channels',
    assistant: {
      use: 'read',
      when: 'List the connected channels (Facebook, Instagram, website chat), their state and which bot answers each.',
    },
    summary: 'Connections and provider readiness',
    query: ChannelListQuery,
    responses: { 200: ChannelListResponse },
  },
  {
    ...scoped,
    method: 'post',
    path: '/channels/{provider}/connect',
    assistant: { use: 'never' },
    summary: 'Start a server-bound Meta consent flow',
    responses: { 201: ConnectChannelResponse },
  },
  {
    ...scoped,
    method: 'get',
    path: '/channels/discoveries/{id}',
    assistant: { use: 'never' },
    summary: 'Accounts granted by Meta',
    responses: { 200: DiscoveryDto },
  },
  {
    ...scoped,
    method: 'post',
    path: '/channels/discoveries/{id}/select',
    assistant: { use: 'never' },
    summary: 'Save selected granted accounts',
    body: SelectChannelRequest,
    responses: { 201: z.object({ data: z.array(ChannelConnectionDto) }) },
  },
  {
    ...scoped,
    method: 'patch',
    path: '/channels/{id}',
    assistant: { use: 'never' },
    summary: 'Bind a bot or disconnect',
    body: UpdateChannelRequest,
    responses: { 200: ChannelConnectionDto },
  },
  {
    ...scoped,
    method: 'delete',
    path: '/channels/{id}',
    assistant: { use: 'never' },
    summary: 'Remove a Facebook or Instagram page (soft delete; history is kept)',
    responses: { 204: null },
  },
  {
    ...scoped,
    method: 'post',
    path: '/channels/website',
    assistant: { use: 'never' },
    summary: 'Create a website chat connection',
    body: CreateWebsiteRequest,
    responses: { 201: ChannelConnectionDto },
  },
  {
    ...scoped,
    method: 'patch',
    path: '/channels/{id}/website',
    assistant: { use: 'never' },
    summary: 'Update website widget settings, name or enabled state',
    body: UpdateWebsiteRequest,
    responses: { 200: ChannelConnectionDto },
  },
  {
    auth: false,
    tag: 'channel',
    method: 'get',
    path: '/channels/oauth/{provider}/callback',
    summary: 'Meta OAuth callback',
    responses: { 200: z.string() },
  },
]);
